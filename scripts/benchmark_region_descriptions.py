def patch(grid, box, palette):
    x,y,r,b=box;im=Image.new('RGB',(r-x+1,b-y+1))
    im.putdata([ImageColor.getrgb(palette[str(grid[yy][xx])]) for yy in range(y,b+1) for xx in range(x,r+1)])
    return im


def card(c,o,palette):
    im=Image.new('RGB',(944,432),'#26313d');draw=ImageDraw.Draw(im)
    overview=patch(c['grid'],[0,0,63,63],palette).resize((384,384),NEAREST)
    im.paste(overview,(16,32));draw.text((16,10),'OVERVIEW: cyan outline = candidate',fill='white')
    x,y,r,b=o['bbox'];draw.rectangle((16+x*6-1,32+y*6-1,16+(r+1)*6,32+(b+1)*6),outline='cyan',width=1)
    near=[max(0,x-4),max(0,y-4),min(63,r+4),min(63,b+4)]
    tiles=[]
    for box,left,title,mark in [(o['bbox'],416,'CANDIDATE: original pixels',False),(near,680,'NEIGHBORHOOD',True)]:
        crop=patch(c['grid'],box,palette);scale=max(1,min(256//crop.width,256//crop.height))
        px=left+(256-crop.width*scale)//2;py=48+(352-crop.height*scale)//2
        im.paste(crop.resize((crop.width*scale,crop.height*scale),NEAREST),(px,py))
        draw.text((left,10),title,fill='white')
        if mark:
            draw.rectangle((px+(x-box[0])*scale-1,py+(y-box[1])*scale-1,
                px+(r-box[0]+1)*scale,py+(b-box[1]+1)*scale),outline='cyan',width=1)
        tiles.append(dict(box=box,offset=[px,py],scale=scale,marked=mark))
    return im,tiles


def iou(a,b):
    inter=max(0,min(a[2],b[2])-max(a[0],b[0])+1)*max(0,min(a[3],b[3])-max(a[1],b[1])+1)
    return inter/(area(a)+area(b)-inter)


def area(b):return (b[2]-b[0]+1)*(b[3]-b[1]+1)
def center(b):return ((b[0]+b[2])/2,(b[1]+b[3])/2)


def collapse(candidates):
    """Conservative equivalent-box collapse; cannot merge disjoint copies."""
    kept=[]
    for o in sorted(candidates,key=lambda o:(area(o['bbox']),o['id'])):
        if not any(iou(o['bbox'],k['bbox'])>=.7 and max(abs(a-b) for a,b in zip(center(o['bbox']),center(k['bbox'])))<=1 for k in kept):
            kept.append(o)
    return kept


def query_plan(c,g):
    class_id=next(k['id'] for k in c['classes'] if g['id'] in k['members'])
    if c['origin']=='synthetic':return dict(class_id=class_id,filter='quadrant',value=g['location'])
    plans={
        'ls20':{'g1':dict(filter='upper'), 'g2':dict(filter='lower_center'), 'g3':dict(filter='bottom'),
                'g4':dict(filter='bottom',rank='left'), 'g5':dict(filter='bottom',rank='middle'),
                'g6':dict(filter='bottom',rank='right'), 'g7':dict(filter='any')},
        'vc33':{'g1':dict(filter='top'), 'g2':dict(filter='right_below_anchor',anchor='class4'),
                'g3':dict(filter='lower'), 'g4':dict(filter='right_above_anchor',anchor='class4'), 'g5':dict(filter='any')},
        'ft09':{'g1':dict(filter='topmost',rank='left'), 'g2':dict(filter='topmost',rank='left'),
                'g3':dict(filter='bottom'), 'g4':dict(filter='topmost',rank='right'),
                'g5':dict(filter='quadrant',value='upper left')}}
    return dict(class_id=class_id,**plans[c['name']][g['id']])


def select(c,plan,matches):
    """No annotation reads. Ambiguous classes/anchors produce no selection."""
    byid={o['id']:o for o in c['candidates']}
    candidates=collapse([byid[i] for i in matches.get(plan['class_id'],[])])
    f=plan['filter']
    if f in ('right_below_anchor','right_above_anchor'):
        anchors=collapse([byid[i] for i in matches.get(plan['anchor'],[])])
        if len(anchors)!=1:return dict(selected=None,reason='anchor_missing_or_ambiguous',remaining=[])
        ay=center(anchors[0]['bbox'])[1]
        candidates=[o for o in candidates if center(o['bbox'])[0]>=48 and
                    ((center(o['bbox'])[1]>ay) if f=='right_below_anchor' else (center(o['bbox'])[1]<ay))]
    elif f=='quadrant':
        upper,left='upper' in plan['value'],'left' in plan['value']
        candidates=[o for o in candidates if (center(o['bbox'])[1]<32)==upper and (center(o['bbox'])[0]<32)==left]
    elif f=='topmost':
        if candidates:
            y=min(center(o['bbox'])[1] for o in candidates)
            candidates=[o for o in candidates if center(o['bbox'])[1]<=y+1]
    elif f!='any':
        predicates={'upper':lambda x,y:y<32,'lower':lambda x,y:y>=32,
            'lower_center':lambda x,y:16<=x<=48 and y>=32,
            'bottom':lambda x,y:y>=56,'top':lambda x,y:y<=8}
        candidates=[o for o in candidates if predicates[f](*center(o['bbox']))]
    remaining=[o['id'] for o in candidates]
    if candidates and 'rank' in plan:
        candidates.sort(key=lambda o:center(o['bbox'])[0])
        if plan['rank']=='middle':
            if len(candidates)!=3:return dict(selected=None,reason='middle_requires_three_instances',remaining=remaining)
            candidates=[candidates[1]]
        else:
            v=center(candidates[0 if plan['rank']=='left' else -1]['bbox'])[0]
            candidates=[o for o in candidates if center(o['bbox'])[0]==v]
    return dict(selected=candidates[0]['id'] if len(candidates)==1 else None,
        reason='unique' if len(candidates)==1 else 'missing_or_ambiguous',remaining=remaining)


def payload(system,content,max_tokens,grammar=None):
    p=dict(model='qwen3-vl-4b-instruct',temperature=0,seed=929710,max_tokens=max_tokens,
        cache_prompt=False,stream=False,messages=[dict(role='system',content=system),dict(role='user',content=content)])
    if grammar:p['grammar']=grammar
    else:p['response_format']={'type':'json_object'}
    return p


def prepare(out):
    out.mkdir(parents=True,exist_ok=False);(out/'cards').mkdir();(out/'sources').mkdir()
    # Corrected source contains identical candidates, with the known ft09 annotation fixed.
    cases=json.loads((CORRECTION/'cases.json').read_text());palette=json.loads(PALETTE.read_text())[0]['palette']
    jobs=[]
    for c in cases:
        c['queries']=[dict(gold_id=g['id'],plan=query_plan(c,g)) for g in c['gold']]
        for o in c['candidates']:
            image,tiles=card(c,o,palette);path=out/'cards'/f'{c["name"]}-{o["id"]}.png';image.save(path)
            o['card']=str(path.relative_to(out));o['tiles']=tiles
            p=payload(DESCRIPTION_SYSTEM,[encode(image),dict(type='text',text='What is the extent and appearance of this candidate?')],160)
            jobs.append(dict(id=f'd{len(jobs)}',stage='describe',case=c['name'],candidate_id=o['id'],payload=p,payload_digest=digest(p)))
    baseline=json.loads((SOURCE/'jobs.json').read_text());corrected=json.loads((CORRECTION/'jobs.json').read_text())
    for j in baseline:
        if j['stage']=='binding' and j['permutation']==0:
            if j['case']=='ft09' and j['gold_id']=='g5':j=next(j for j in corrected if j['permutation']==0)
        elif j['stage']=='discovery' and j['arm']=='concept_only_4':pass
        else:continue
        j=deepcopy(j);j['original_id']=j['id'];j['id']='b'+str(j['id']);j['stage']='baseline_'+j['stage'];jobs.append(j)
    paths=[Path(__file__),ROOT/'scripts/benchmark_concept_binding_split.py']
    for p in paths:(out/'sources'/p.name).write_bytes(p.read_bytes())
    save(out/'cases.json',cases);save(out/'description-jobs.json',jobs)
    save(out/'plan.json',dict(created=datetime.now(timezone.utc).isoformat(),cases=len(cases),candidates=sum(len(c['candidates']) for c in cases),
        cases_digest=digest(cases),description_jobs_digest=digest(jobs),sources={str(p):sha(p) for p in paths},
        inputs={str(p):sha(p) for p in [SOURCE/'jobs.json',CORRECTION/'cases.json',CORRECTION/'jobs.json',PALETTE]},
        images={str(p.relative_to(out)):sha(p) for p in (out/'cards').glob('*.png')},
        stages='A: query-free local candidate descriptions, host attaches ID. B: for each valid whole-object description, one text-only appearance quiz per requested class plus one absent-class control. C: host applies manually parsed spatial query plan, collapses near-equivalent boxes, otherwise abstains. All 192 candidates described; no gold shortlist. B requests frozen after A, before any B calls.',
        rubric='Binding: same >=90% target support, bbox IoU>=.5, area<=2x as prior evaluation. Primary comparable set is 36 targets excluding previous annotation-error target; report all37 separately with corrected target in BOTH arms. Candidate-level semantic review by implementing assistant on all gold-eligible candidate descriptions; whole-object description must contain distinguishing colors and shape/pattern. For class recall, one accurate eligible whole description suffices; do not count duplicates as new classes. Model textual agreement alone is not semantic gold.',
        spatial='Hand-authored decomposition of target language, not inferred from gold boxes: half-plane/quadrant cut32, top8, bottom56, right48, lower-center x16..48. topmost row within1 center pixel; middle needs exactly3 boxes; anchors require one collapsed matched region. Equivalent boxes IoU>=.7 and center difference<=1; smallest area represents cluster. Unknown roles unconditionally unresolved because no actions exist.',
        limits='Reused 8 frames, real partial annotation, no repeated seeds. Larger image/call/output budget than baseline; evaluate full-frame costs separately. Oracle appearance queries and manually compiled spatial clauses remain inputs to B/C; not autonomous concept clustering, role inference, tracking, or live gameplay. All-stage/class failures remain counted. No prompt tuning after responses.'))
    print('Prepared',len(jobs),'description/baseline jobs',flush=True)


def verify(out):
    plan=json.loads((out/'plan.json').read_text());cases=json.loads((out/'cases.json').read_text())
    jobs=json.loads((out/'description-jobs.json').read_text())
    assert digest(cases)==plan['cases_digest'] and digest(jobs)==plan['description_jobs_digest']
    for p,h in {**plan['sources'],**plan['inputs']}.items():assert sha(Path(p))==h,p
    for p,h in plan['images'].items():assert sha(out/p)==h,p
    for j in jobs:assert digest(j['payload'])==j['payload_digest']
    return plan,cases,jobs


def run(out,base,stage):
    parsed=urlparse(base);assert parsed.scheme=='http' and parsed.hostname in ('127.0.0.1','localhost')
    _,_,jobs=verify(out)
    if stage=='match':
        jobs=json.loads((out/'match-jobs.json').read_text());manifest=json.loads((out/'match-plan.json').read_text())
        assert digest(jobs)==manifest['jobs_digest'] and sha(out/'description-responses.jsonl')==manifest['source_response_sha256']
    assert not (out/f'{stage}-responses.jsonl').exists(),'Never overwrite measured responses'
    save(out/f'{stage}-server-before.json',http(base,'/props'));random.Random(929711).shuffle(jobs)
    started=time.monotonic()
    with (out/f'{stage}-responses.jsonl').open('x') as stream:
        for i,j in enumerate(jobs):
            r={k:v for k,v in j.items() if k not in ('payload','acceptable')};start=time.monotonic()
            try:
                response=http(base,'/v1/chat/completions',j['payload'])
                r.update(response=response,answer=response['choices'][0]['message']['content'])
            except Exception as exc:r.update(error=f'{type(exc).__name__}: {exc}',answer='')
            r['seconds']=time.monotonic()-start;stream.write(json.dumps(r)+'\n');stream.flush()
            if i%10==0 or r.get('error'):print(i+1,'/',len(jobs),j['case'],j['stage'],round(time.monotonic()-started,1),r.get('error',''),flush=True)
    save(out/f'{stage}-server-after.json',http(base,'/props'));save(out/f'{stage}-health.json',http(base,'/health'))
    print('Completed',stage,len(jobs),'seconds',round(time.monotonic()-started,2),flush=True)


def descriptions(out):
    _,cases,jobs=verify(out);rows=list(map(json.loads,(out/'description-responses.jsonl').read_text().splitlines()))
    assert Counter(r['id'] for r in rows)==Counter(j['id'] for j in jobs)
    result=[]
    for r in rows:
        if r['stage']!='describe':continue
        valid=False;value={}
        try:
            value=json.loads(r['answer']);valid=(isinstance(value,dict) and value.get('extent') in ['whole','part','multiple','background','unclear']
                and isinstance(value.get('appearance'),str) and bool(value['appearance'].strip())
                and r['response']['choices'][0]['finish_reason']=='stop' and not r.get('error'))
        except (ValueError,TypeError,KeyError):pass
        result.append(dict(id=r['id'],case=r['case'],candidate_id=r['candidate_id'],valid=bool(valid),
            extent=value.get('extent','invalid') if isinstance(value,dict) else 'invalid',
            appearance=value.get('appearance','') if isinstance(value,dict) else '',seconds=r['seconds']))
    return cases,rows,result


def prepare_match(out):
    cases,rows,desc=descriptions(out);jobs=[]
    assert not (out/'match-jobs.json').exists(),'Match schedule already frozen'
    for d in desc:
        if not d['valid'] or d['extent']!='whole':continue
        c=next(c for c in cases if c['name']==d['case'])
        for kind in c['classes']+[dict(id='absent',description='Solid magenta triangular object.')]:
            content='Requested type: '+kind['description']+'\nStored appearance: '+d['appearance']
            p=payload(MATCH_SYSTEM,content,1,'root ::= "1" | "2" | "8"')
            jobs.append(dict(id=f'm{len(jobs)}',stage='match',case=c['name'],candidate_id=d['candidate_id'],
                class_id=kind['id'],payload=p,payload_digest=digest(p)))
    save(out/'descriptions.json',desc);save(out/'match-jobs.json',jobs)
    save(out/'match-plan.json',dict(created=datetime.now(timezone.utc).isoformat(),jobs_digest=digest(jobs),
        source_response_sha256=sha(out/'description-responses.jsonl'),requests=len(jobs),
        whole_candidates=sum(d['valid'] and d['extent']=='whole' for d in desc),policy='Frozen whole-object gate; no human/gold filtering or rewritten descriptions.'))
    print('Prepared',len(jobs),'text-only matching requests',Counter(d['extent'] for d in desc),flush=True)


def analyze(out):
    cases,baseline,desc=descriptions(out);dby={(d['case'],d['candidate_id']):d for d in desc}
    match=list(map(json.loads,(out/'match-responses.jsonl').read_text().splitlines()));jobs=json.loads((out/'match-jobs.json').read_text())
    assert Counter(r['id'] for r in match)==Counter(j['id'] for j in jobs)
    found={c['name']:{} for c in cases}
    for r in match:
        if r['answer'].strip()=='1' and not r.get('error'):found[r['case']].setdefault(r['class_id'],[]).append(r['candidate_id'])
    scored=[];oracle=[];candidates_for_review=[]
    for c in cases:
        oracle_matches={k['id']:[o['id'] for o in c['candidates'] if any(eligible(o,g) for g in c['gold'] if g['id'] in k['members'])] for k in c['classes']}
        for o in c['candidates']:
            covered=[g['id'] for g in c['gold'] if eligible(o,g)]
            if covered:candidates_for_review.append(dict(case=c['name'],candidate_id=o['id'],gold_ids=covered,
                **{k:dby[c['name'],o['id']][k] for k in ['appearance','extent','valid']}))
        for q in c['queries']:
            g=next(g for g in c['gold'] if g['id']==q['gold_id']);result=select(c,q['plan'],found[c['name']])
            actual=next((o for o in c['candidates'] if o['id']==result['selected']),None)
            old=next(r for r in baseline if r['stage']=='baseline_binding' and r['case']==c['name'] and r['gold_id']==q['gold_id'])
            old_candidate=next((o for o in c['candidates'] if o['id']==old['answer'].strip()),None)
            scored.append(dict(case=c['name'],origin=c['origin'],gold_id=g['id'],plan=q['plan'],**result,
                correct=bool(actual and eligible(actual,g)),baseline_selected=old['answer'].strip(),baseline_correct=bool(old_candidate and eligible(old_candidate,g)),
                class_matches=found[c['name']].get(q['plan']['class_id'],[]),comparable=not(c['name']=='ft09' and g['id']=='g5')))
            ideal=select(c,q['plan'],oracle_matches);obj=next((o for o in c['candidates'] if o['id']==ideal['selected']),None)
            oracle.append(dict(case=c['name'],gold_id=g['id'],**ideal,correct=bool(obj and eligible(obj,g))))
    save(out/'binding-scores.json',scored);save(out/'oracle-geometry.json',oracle);save(out/'semantic-review-input.json',candidates_for_review)
    summary=dict(primary={},all_corrected={},extent_counts=dict(Counter(d['extent'] for d in desc)),
        descriptor_valid=sum(d['valid'] for d in desc),descriptor_total=len(desc),
        geometry_oracle=dict(correct=sum(r['correct'] for r in oracle),total=len(oracle)),
        calls=dict(description=len(desc),matching=len(match),baseline=sum(r['stage'].startswith('baseline') for r in baseline)),
        errors=[dict(id=r['id'],error=r['error']) for r in baseline+match if r.get('error')],
        timing=dict(description_total_seconds=sum(d['seconds'] for d in desc),matching_total_seconds=sum(r['seconds'] for r in match),
            description_median_seconds=statistics.median(d['seconds'] for d in desc),matching_median_seconds=statistics.median(r['seconds'] for r in match)))
    for key,comparable in [('primary',True),('all_corrected',False)]:
        for group in ['all','synthetic','real']:
            rr=[r for r in scored if (not comparable or r['comparable']) and (group=='all' or (r['origin']=='synthetic')==(group=='synthetic'))]
            summary[key][group]=dict(total=len(rr),correct=sum(r['correct'] for r in rr),baseline_correct=sum(r['baseline_correct'] for r in rr),
                abstentions=sum(r['selected'] is None for r in rr),wrong_selection=sum(not r['correct'] and r['selected'] is not None for r in rr))
    summary['controls']=[]
    for c in cases:
        selected=collapse([o for o in c['candidates'] if o['id'] in found[c['name']].get('absent',[])])
        summary['controls'].append(dict(case=c['name'],kind='absent',correct=not selected,selections=[o['id'] for o in selected]))
    summary['role_controls']='Unresolved by host policy; not evidence of learned role recognition.'
    save(out/'summary.json',summary);print(json.dumps(summary,indent=2))


if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('command',choices=['prepare','run-description','prepare-match','run-match','analyze'])
    p.add_argument('--out',type=Path,required=True);p.add_argument('--base',default='http://127.0.0.1:8080');a=p.parse_args()
    if a.command=='prepare':prepare(a.out)
    elif a.command=='prepare-match':prepare_match(a.out)
    elif a.command=='analyze':analyze(a.out)
    else:run(a.out,a.base,'description' if a.command=='run-description' else 'match')
